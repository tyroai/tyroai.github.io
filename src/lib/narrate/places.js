// Kısa adda (≤ 4 harf) yalnız yer ekleri: "akraba" Akra, "roman" Roma sayılmasın.
const SHORT_SUFFIX = [
  "",
  "a",
  "e",
  "ya",
  "ye",
  "da",
  "de",
  "ta",
  "te",
  "dan",
  "den",
  "ki",
  "daki",
  "deki",
]
const near = (w, root) =>
  root.length > 4 ? stem(w, root, 5) : SHORT_SUFFIX.some((sf) => w === root + sf)

/** Kelimelerdeki yer: `{ code, abroad }` — ERP konumu ya da yurt dışı için "Diğer"; yoksa null. */
export function placeOf(list) {
  for (const w of list) {
    const local = LOCAL.find(([root]) => near(w, root))
    if (local) return { code: local[1], abroad: false }
    if (DOMESTIC.some((root) => near(w, root))) return { code: OTHER_LOCATION, abroad: false }
    if (ABROAD.some((root) => near(w, root))) return { code: OTHER_LOCATION, abroad: true }
  }
  return null
}
